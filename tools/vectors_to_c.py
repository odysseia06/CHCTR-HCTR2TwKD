"""JSON-to-C fixture generator.  Runs as a Meson custom_target; output is a
build artifact, never committed.  Accepts only schema-valid canonical input;
emission is deterministic (no timestamps, no machine paths).

Usage: vectors_to_c.py CHCTR2_JSON TWKD_JSON OUTPUT_C
"""

import json
import sys

SCHEMA = "chctr-hctr2twkd-v1"


def field_bytes(v, field):
    s = v[field]
    assert s == s.lower() and len(s) % 2 == 0, (v["id"], field)
    return bytes.fromhex(s)


def emit_profile(out, path, prefix, cname, expect_profile):
    with open(path) as f:
        doc = json.load(f)
    assert doc["schema"] == SCHEMA, doc["schema"]
    assert doc["profile"] == expect_profile, doc["profile"]
    vecs = doc["vectors"]
    assert vecs == sorted(vecs, key=lambda v: v["id"])
    for i, v in enumerate(vecs):
        for field in ("key", "tweak", "plaintext", "ciphertext"):
            data = field_bytes(v, field)
            out.append(f"static const u8 {prefix}{i}_{field}[] = {{")
            if not data:
                out.append("\t0x00,  /* empty; length tracked separately */")
            for j in range(0, len(data), 12):
                out.append("\t" + " ".join(f"0x{b:02x}," for b in
                                           data[j:j + 12]))
            out.append("};")
    out.append(f"const struct conf_vec {cname}[] = {{")
    for i, v in enumerate(vecs):
        key = field_bytes(v, "key")
        tweak = field_bytes(v, "tweak")
        pt = field_bytes(v, "plaintext")
        ct = field_bytes(v, "ciphertext")
        assert len(pt) == len(ct) and len(pt) >= 16, v["id"]
        out.append(f"\t{{ .id = \"{v['id']}\",")
        out.append(f"\t  .key = {prefix}{i}_key, .key_len = {len(key)},")
        out.append(f"\t  .tweak = {prefix}{i}_tweak, "
                   f".tweak_len = {len(tweak)},")
        out.append(f"\t  .plaintext = {prefix}{i}_plaintext,")
        out.append(f"\t  .ciphertext = {prefix}{i}_ciphertext, "
                   f".len = {len(pt)} }},")
    out.append("};")
    out.append(f"const size_t {cname}_count = {len(vecs)};")
    out.append("")


def main():
    chctr2_json, twkd_json, out_path = sys.argv[1:4]
    out = ["/* GENERATED by tools/vectors_to_c.py from "
           "test_vectors/reference/v1 -- DO NOT EDIT */",
           "#include \"conformance_vectors.h\"", ""]
    emit_profile(out, chctr2_json, "chctr2_v", "chctr2_conf_tv",
                 "chctr2-aes256-polyval-v1")
    emit_profile(out, twkd_json, "twkd_v", "twkd_conf_tv",
                 "hctr2-twkd-cenc126-aes256-polyval-v1")
    with open(out_path, "w") as f:
        f.write("\n".join(out) + "\n")


main()
